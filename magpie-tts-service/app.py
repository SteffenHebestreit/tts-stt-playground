"""Magpie-TTS text-to-speech service (NVIDIA NeMo).

Wraps NVIDIA's Magpie-TTS Multilingual (``nvidia/magpie_tts_multilingual_357m``, NVIDIA
Open Model License): five built-in speakers, no voice cloning, no streaming. Endpoints
follow the project's ``simple-json-tts-v1`` and ``speaker-catalog-v1`` contracts, so
the frontend gateway proxies it like the other providers.

Four properties of the model shape most of this file (measured with nemo_toolkit 3.0.0):

- ``do_tts`` silently reads any language it has no tokenizer for with English rules, and
  drops every digit unless text normalization is on. The language is therefore validated
  here, against the tokenizers the loaded model really has, and normalization defaults on.
- NeMo decodes at most ~23 s of audio (500 frames) per chunk of text, and above a
  per-language threshold it chunks the text itself, ending chunks by force. Long text is
  therefore cut here into groups of whole sentences, each short enough to stay a single
  NeMo chunk in its language (Chinese and Japanese at their own sentence marks), and
  each generated by its own ``do_tts`` call (see text_splitting.py). A group whose audio
  still fills the frame limit was cut off, and is generated again in two halves.
- The first call per language builds that language's text normalizer (12-48 s), so the
  first load runs one short warm-up generation in the default language (and in
  MAGPIE_WARM_LANGUAGES). The normalizers stay in host RAM across idle unloads, so a
  reload repeats neither the warm-up nor a normalizer build.
- ``do_tts`` runs in a worker thread that cannot be cancelled. Whatever the thread uses
  (the model reference, the single-flight lock) is released when the THREAD finishes,
  never when the awaiting coroutine goes away, and the thread is told to stop after its
  current group. A request is abandoned when its client's connection closes (a hang-up,
  or the gateway's read timeout); uvicorn and Starlette never cancel a handler by
  themselves.
"""

