@app.get("/ready")
async def ready():
    """Readiness: can this service take a request now?

    200 once a load has ever succeeded (a later idle unload does not flip it) and while
    nothing is known to be wrong. 503 with a JSON `reason` while the first load runs
    (`loading`, with `Retry-After`) and when it failed and never succeeded (`load_failed`;
    `detail` is a short category, never the exception text, which can hold paths: that is
    in the log). Only reads state; never triggers or waits for a load.
    """
    state = _model_slot.readiness()
    if _preload_pending and not state["ever_loaded"] and state["reason"] == "ok":
        state = {**state, "ready": False, "reason": "loading"}
    body = {
        "ready": state["ready"],
        "reason": state["reason"],
        "model_resident": state["resident"],
        "model_ever_loaded": state["ever_loaded"],
        "current_model": public_model_name(MODEL_NAME),
        "device": device,
    }
    if state["detail"]:
        body["detail"] = state["error_category"] or "load_error"
    if state["ready"]:
        return body
    headers = {"Retry-After": "5"} if state["reason"] == "loading" else None
    return JSONResponse(content=body, status_code=503, headers=headers)


@app.post("/unload")
async def unload():
    """Release the model and its VRAM now, without stopping the container.

    200 when released or already unloaded; **409 while a request is in flight** (including
    a generation whose client already left), because freeing memory a running generation
    still reads would crash the worker. The next request reloads transparently.
    """
    result = await _model_slot.try_unload_async()
    if result["reason"] == "busy":
        return JSONResponse(status_code=409, content={"detail": "Model is in use; retry when idle", **result})
    return {"model_resident": _model_slot.resident, **result}


