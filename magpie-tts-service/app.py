class TTSRequest(BaseModel):
    """Request body for built-in-speaker synthesis (simple-json-tts-v1)."""

    text: str
    language: str = "auto"
    # A speaker name (any case) or its index; blank or "auto" is MAGPIE_DEFAULT_SPEAKER.
    # Strict, because pydantic would otherwise turn a JSON `true` into speaker 1 and answer 200.
    speaker: Optional[Union[StrictStr, StrictInt]] = None


@app.post("/tts")
async def text_to_speech(request: TTSRequest, http_request: Request = None):
    """Generate speech with one of the built-in speakers.

    The text is cut into groups of whole sentences, each short enough to stay a single
    NeMo chunk (NeMo decodes at most ~23 s of audio per chunk), generated on its own and
    joined with a short pause. A group whose audio fills that limit is generated again in
    two halves. When the client's connection closes first (a hang-up, or the gateway's
    read timeout) the generation stops after its current group: 499.
    """
    text = _require_text(request.text)
    try:
        language = resolve_language(request.language, DEFAULT_LANGUAGE, _supported_now())
    except LanguageNotSupported as e:
        raise HTTPException(status_code=400, detail=str(e))
    labels = _labels_now()
    try:
        speaker_index = resolve_speaker(request.speaker, labels, _default_speaker(labels))
    except SpeakerNotFound as e:
        raise HTTPException(status_code=400, detail=str(e))

    groups = group_text(text, language, MAX_GROUP_CHARS)
    started = time.monotonic()
    try:
        samples, sample_rate, pieces = await _generate_for(http_request, groups, language, speaker_index)
        elapsed = time.monotonic() - started
    except HTTPException:
        raise
    except _GenerationCancelled:
        logger.info(
            "/tts client went away after %.1fs; the remaining groups of %d were not generated",
            time.monotonic() - started, len(groups),
        )
        raise HTTPException(status_code=499, detail="Request cancelled")
    except Exception as e:
        raise _server_error(e)

    if samples.size == 0:
        raise HTTPException(
            status_code=400,
            detail="The text produced no audio (is it only punctuation or symbols the model cannot speak?)",
        )
    logger.info("/tts generated %d chars in %d piece(s) in %.2fs", len(text), pieces, elapsed)
    return _wav_response(samples, sample_rate, {
        "X-Language": language,
        "X-Speaker": labels[speaker_index],
        "X-Chunk-Count": str(pieces),
        "X-Generation-Time": f"{elapsed:.3f}",
    })


