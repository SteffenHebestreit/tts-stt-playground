allow_credentials = os.getenv("ALLOW_CREDENTIALS", "false").strip().lower() in {"1", "true", "yes", "on"}
if "*" in allowed_origins and allow_credentials:
    allow_credentials = False

# FastAPI parses the whole JSON body before a handler runs, so a size check inside the
# handler comes after the cost was paid; body_limit.py checks the declared Content-Length
# AND counts the bytes that arrive. Each add_middleware wraps what was added before it:
# the body limit is innermost, the origin guard (403 for a state-changing request with a
# foreign Origin header; no Origin, e.g. the gateway or curl, is unaffected) next, CORS
# outermost so a 403/413 still carries the headers a listed origin needs to read it.
app.add_middleware(BodyLimitMiddleware, limit_for=_body_limit)
app.add_middleware(OriginGuardMiddleware, allowed_origins=allowed_origins)
if allowed_origins:
    app.add_middleware(
        CORSMiddleware,
        allow_origins=allowed_origins,
        allow_credentials=allow_credentials,
        allow_methods=["*"],
        allow_headers=["*"],
    )


