def _default_speaker(labels: list) -> int:
    """The configured default speaker's index, or the first speaker if the model has fewer speakers than that."""
    return _DEFAULT_SPEAKER_INDEX if _DEFAULT_SPEAKER_INDEX < len(labels) else 0


def _require_text(text: Optional[str]) -> str:
    """400 for a missing/blank text field, 413 past MAX_TEXT_CHARS."""
    if not text or not text.strip():
        raise HTTPException(status_code=400, detail="Text not provided")
    if len(text) > MAX_TEXT_CHARS:
        raise HTTPException(
            status_code=413,
            detail=f"Text is {len(text)} characters; the limit is {MAX_TEXT_CHARS} (raise it with MAX_TEXT_CHARS).",
        )
    return text


def _safe_header(value: str) -> str:
    """A string made safe for an HTTP header value: latin-1, no control characters, no space at either end.

    The headers go out after the audio has been generated, and h11 refuses a value that
    breaks any of these rules, so the finished response would never reach the caller.
    """
    value = (value or "").encode("latin-1", "replace").decode("latin-1")
    return re.sub(r"[\x00-\x1f\x7f]", " ", value).strip()


def _wav_response(audio: np.ndarray, sample_rate: int, extra_headers: Optional[dict] = None) -> StreamingResponse:
    buffer = io.BytesIO()
    sf.write(buffer, audio, sample_rate, format="WAV")
    buffer.seek(0)
    headers = {"X-Sample-Rate": str(sample_rate)}
    if extra_headers:
        headers.update({k: _safe_header(v) for k, v in extra_headers.items()})
    return StreamingResponse(buffer, media_type="audio/wav", headers=headers)


# --- Generation ----------------------------------------------------------------------

class _GenerationCancelled(Exception):
    """The request went away; the remaining groups were not generated."""


def _as_samples(audio, length) -> np.ndarray:
    """``do_tts`` output (a (1, T) tensor and its length) as a 1-D float32 array, cut to its length."""
    if hasattr(audio, "detach"):
        audio = audio.detach().float().cpu().numpy()
    if hasattr(length, "detach"):
        length = length.detach().cpu().numpy()
    samples = np.asarray(audio, dtype=np.float32).reshape(-1)
    return samples[: int(np.asarray(length).reshape(-1)[0])]


def _decoder_cap_samples(model) -> int:
    """The most samples one NeMo chunk can come back with; 0 (no check) when the model does not say.

    The decoder stops after ``max_decoder_steps`` frames (taken ``frame_stacking_factor``
    at a time) whether or not the speech is finished, and returns what it has without an
    error. 512000 samples (23.2 s) for the released checkpoint: 500 frames of 1024.
    """
    try:
        frames = int(model.inference_parameters.max_decoder_steps)
        stacking = max(1, int(getattr(model, "frame_stacking_factor", 1) or 1))
        return frames // stacking * stacking * int(model.codec_model_samples_per_frame)
    except (AttributeError, TypeError, ValueError):
        return 0


def _synthesize(model, groups, language: str, speaker_index: int, cancel: threading.Event):
    """Generate *groups* one after the other; returns ``(samples, sample_rate, pieces)``. Runs in a worker thread.

    Audio that fills the decoder's frame limit was almost certainly cut off mid-speech
    (number-heavy text grows a lot under normalization), so that group is generated again
    in two halves and its first audio is dropped. A half that fills the limit as well is
    kept, with a warning: a generation that never stops cannot be fixed by splitting, and
    an answer that is too short beats a 500. *pieces* counts the generations joined.
    """
    sample_rate = int(getattr(model, "output_sample_rate", None) or getattr(model, "sample_rate", None) or 22050)
    cap = _decoder_cap_samples(model)
    parts = []
    # (label for the log, text, may it still be split)
    pending = collections.deque((str(number), group, True) for number, group in enumerate(groups, 1))
    with _MODEL_LOCK:
        while pending:
            label, text, may_split = pending.popleft()
            if cancel.is_set():
                raise _GenerationCancelled()
            audio, length = model.do_tts(
                text, language=language, apply_TN=APPLY_TN, use_cfg=USE_CFG, speaker_index=speaker_index,
            )
            samples = _as_samples(audio, length)
            if cap and samples.size >= cap:
                halves = halve_group(text, language) if may_split else []
                if len(halves) > 1:
                    logger.warning(
                        "Group %s of %d (%d characters) filled the decoder's limit of %d samples (%.1f s) "
                        "and was probably cut off; generating it again as %d pieces.",
                        label, len(groups), len(text), cap, cap / sample_rate, len(halves),
                    )
                    pending.extendleft(reversed([
                        (f"{label}.{number}", half, False) for number, half in enumerate(halves, 1)
                    ]))
                    continue
                logger.warning(
                    "Group %s of %d (%d characters) filled the decoder's limit of %d samples (%.1f s); "
                    "its end may be missing.",
                    label, len(groups), len(text), cap, cap / sample_rate,
                )
            parts.append(samples)
    return join_audio(parts, sample_rate, GROUP_GAP_MS), sample_rate, len(parts)


def _generation_finished(lease, fut) -> None:
    """Runs on the event loop when the worker thread is really done."""
    lease.release_soon()
    if not fut.cancelled():
        fut.exception()  # mark retrieved: the awaiting request may be long gone


async def _run_generation(groups, language: str, speaker_index: int):
    """Generate on the worker pool; returns ``(samples, sample_rate, pieces)``.

    Admission first (503 at once when the queue is full, before the model is touched),
    then a turn (503 after TTS_QUEUE_TIMEOUT_S). The model reference is the thread's
    own and goes back from its completion callback, so cancelling the caller (which
    ``_generate_for`` does when the client's connection closes) can neither let the idle
    reaper or /unload free weights the thread is still reading, nor start a second
    generation next to it. A caller cancelled while queued leaves the queue at once.
    """
    cancel = threading.Event()
    with _gate.admit():
        async with _gate.turn():
            lease = await _model_slot.acquire_lease()
            try:
                fut = asyncio.get_running_loop().run_in_executor(
                    None, functools.partial(_synthesize, lease.model, groups, language, speaker_index, cancel),
                )
            except BaseException:
                lease.release_soon()
                raise
            fut.add_done_callback(functools.partial(_generation_finished, lease))
            try:
                return await asyncio.shield(fut)
            except asyncio.CancelledError:
                cancel.set()
                raise


async def _client_gone(http_request: Request) -> None:
    """Return once the client has closed the connection (the same check as piper-tts-service's)."""
    while True:
        message = await http_request.receive()
        if message["type"] == "http.disconnect":
            return


async def _generate_for(http_request: Optional[Request], groups, language: str, speaker_index: int):
    """``_run_generation`` for a client, given up when that client's connection closes first.

    uvicorn and Starlette never cancel a handler whose client went away; they only answer
    its next ``receive()`` with ``http.disconnect``. Without this, a request the gateway
    had stopped waiting for (its read timeout) kept its queue place and generated all its
    remaining groups for nobody. Cancelling ``_run_generation`` takes a queued request
    out of the queue before it loads or generates anything, and stops a running one after
    its current group (the lease and the model lock stay with the thread until then).
    Raises ``_GenerationCancelled`` when the client left first. Without a request (a direct
    call) this is ``_run_generation``.
    """
    if http_request is None:
        return await _run_generation(groups, language, speaker_index)
    work = asyncio.ensure_future(_run_generation(groups, language, speaker_index))
    gone = asyncio.ensure_future(_client_gone(http_request))
    try:
        await asyncio.wait({work, gone}, return_when=asyncio.FIRST_COMPLETED)
    finally:
        # Also when this handler is cancelled itself: the generation must not outlive it.
        gone.cancel()
        if not work.done():
            work.cancel()
            await asyncio.gather(work, return_exceptions=True)
    if work.cancelled():
        raise _GenerationCancelled()
    return work.result()


