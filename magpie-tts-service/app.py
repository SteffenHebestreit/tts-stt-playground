# --- Configuration -------------------------------------------------------------------

device = "cuda" if torch.cuda.is_available() else "cpu"

# A Hugging Face repo id / NGC name, or the path of a .nemo file on a mounted volume.
MODEL_NAME = (os.getenv("MAGPIE_MODEL") or "nvidia/magpie_tts_multilingual_357m").strip()

# What "auto" (and a blank language) resolves to. Validated against the loaded model's
# tokenizers on every request, so a default the model cannot speak fails loudly.
DEFAULT_LANGUAGE = normalize_language(os.getenv("MAGPIE_DEFAULT_LANGUAGE")) or "de"

# Text normalization (nemo_text_processing): numbers, dates, times and units become
# words. Off, the model's tokenizer drops every digit, so only turn it off for input
# that is already written out.
APPLY_TN = env_flag("MAGPIE_APPLY_TN", True)
USE_CFG = env_flag("MAGPIE_USE_CFG", True)  # classifier-free guidance: better speech, ~2x compute

# Longest group of whole sentences handed to one do_tts call (Chinese and Japanese get a
# third of it). Short enough to stay a single NeMo chunk in every supported language:
# above about 250 an English group crosses NeMo's 45-word threshold and NeMo chunks it
# itself again, so a larger value is ignored like a malformed one.
MAX_GROUP_CHARS = env_number("MAGPIE_MAX_GROUP_CHARS", 200, cast=int, minimum=40, maximum=250)
GROUP_GAP_MS = env_number("MAGPIE_GROUP_GAP_MS", 150, cast=int, minimum=0)

MAX_TEXT_CHARS = env_number("MAX_TEXT_CHARS", 5000, cast=int, minimum=1)

# Further languages to warm at the first load, besides the default one. The first
# request in a language builds that language's text normalizer: measured on an RTX 4080,
# de 12 s, en 18 s, fr 37 s, es 48 s, and every later request in it is an ordinary one.
# Warming moves that wait from the first user to the first load, the only one during
# which /ready answers 503 "loading". A normalizer, whether the warm-up or a request
# built it, stays in host RAM across idle unloads (a few hundred MB per language, no
# VRAM), so a reload after TTS_MODEL_TTL repeats neither the warm-up nor a build.
WARM_LANGUAGES = [
    code for code in (normalize_language(item) for item in (os.getenv("MAGPIE_WARM_LANGUAGES") or "").split(","))
    if code
]

SPEAKER_NAMES = parse_speakers(os.getenv("MAGPIE_SPEAKERS"))
DEFAULT_SPEAKER = (os.getenv("MAGPIE_DEFAULT_SPEAKER") or "Sofia").strip()
# Resolved once, so a misconfigured default is one warning at start, not one per request.
_DEFAULT_SPEAKER_INDEX = default_speaker_index(DEFAULT_SPEAKER, list(SPEAKER_NAMES))

# What the checkpoint is known to hold until a model has been loaded and can say: the
# documented languages, and exactly the configured speaker names (the model's own count,
# once known, pads or trims that list).
_state_lock = threading.Lock()
_supported: list = list(DOCUMENTED_LANGUAGES)
_speaker_count: Optional[int] = None

tts_model = None
model_loaded = False
# A startup preload has been scheduled and has not finished: /ready reports "loading"
# for that window instead of "ready, never loaded".
_preload_pending = False

# Admission (model_lifecycle.RequestGate): TTS_MAX_CONCURRENCY generations at once (the
# model cannot run two at the same time, so more than 1 only queues), TTS_MAX_QUEUE
# more may wait, and none waits longer than TTS_QUEUE_TIMEOUT_S. A request beyond that
# is answered 503 + Retry-After instead of hanging.
_GEN_CONCURRENCY = env_number("TTS_MAX_CONCURRENCY", 1, cast=int, minimum=1)
_MAX_QUEUE = env_number("TTS_MAX_QUEUE", 4 * _GEN_CONCURRENCY, cast=int, minimum=0)
_QUEUE_TIMEOUT_S = env_number("TTS_QUEUE_TIMEOUT_S", 60.0, cast=float, minimum=0.1)
_RETRY_AFTER_S = 5

# `do_tts` mutates per-call state on the shared model, so two threads must never be in
# it together, whatever the gate says (a cancelled request frees its turn while its
# thread is still finishing the current group).
_MODEL_LOCK = threading.Lock()


def _failure(status_code: int, public: str, detail: object = None, *, exc_info: bool = False) -> HTTPException:
    """An error for the client that says *public* and a request id, nothing else.

    The exception text (library messages carry paths, URLs and shapes) goes to the log
    under the same id, so an operator can find it and a caller cannot read the
    container's internals out of an unauthenticated response.
    """
    request_id = uuid.uuid4().hex[:12]
    logger.error("[request %s] %s: %s", request_id, public, detail, exc_info=exc_info)
    return HTTPException(
        status_code=status_code,
        detail=f"{public} (request id {request_id}).",
        headers={"X-Request-ID": request_id},
    )


def _busy(reason: str) -> HTTPException:
    if reason == "queue_timeout":
        detail = (
            f"The service is busy: this request waited {_QUEUE_TIMEOUT_S:g} s for its turn "
            f"(TTS_QUEUE_TIMEOUT_S). Retry shortly."
        )
    else:
        detail = (
            f"The service is busy: {_MAX_QUEUE + _GEN_CONCURRENCY} requests are already in progress "
            f"or waiting (TTS_MAX_CONCURRENCY + TTS_MAX_QUEUE). Retry shortly."
        )
    return HTTPException(status_code=503, detail=detail, headers={"Retry-After": str(_RETRY_AFTER_S)})


_gate = RequestGate(_GEN_CONCURRENCY, _MAX_QUEUE, _QUEUE_TIMEOUT_S, busy=_busy)


def _server_error(exc: Exception) -> HTTPException:
    """The HTTP failure for an unexpected exception; out-of-memory is not a 500."""
    if is_cuda_oom(exc):
        with suppress(Exception):
            if device == "cuda":
                torch.cuda.empty_cache()
        logger.error("GPU out of memory while generating speech: %s", exc)
        return HTTPException(
            status_code=503,
            detail=(
                "GPU out of memory while generating speech. Send shorter text or free the VRAM another "
                "service holds (POST /unload on it)."
            ),
            headers={"Retry-After": str(_RETRY_AFTER_S)},
        )
    return _failure(500, "Speech generation failed", exc, exc_info=True)


# --- Model ---------------------------------------------------------------------------

# Text normalizers by language, for the life of the process. NeMo 3.0.0 builds one on a
# language's first apply_TN call (pynini grammars, 12-48 s) and keeps it on the model
# INSTANCE, so every idle unload threw them away and the next load built them again, in
# front of whichever request caused it. They are CPU-only (a few hundred MB of host RAM
# per language), hold no reference to the model and have nothing to do with the VRAM an
# unload frees, so every instance is given this one dict. That is safe because every
# do_tts runs under _MODEL_LOCK, the slot's reference count rules out a reload during a
# generation, and NeMo is pinned below 3.1 (the attribute is NeMo 3.0's).
_TEXT_NORMALIZERS: dict = {}


def _share_text_normalizers(model) -> None:
    """Hand a newly loaded model the normalizers that earlier loads and requests built.

    NeMo stores None for a build that failed and from then on reads that language without
    normalization, silently dropping every digit; those entries are removed, so the new
    load tries again. A model without the attribute (another NeMo layout) is left alone
    and simply warms up on every load, as before.
    """
    own = getattr(model, "_text_normalizers", None)
    if not isinstance(own, dict):
        return
    with _MODEL_LOCK:
        for code in [code for code, normalizer in _TEXT_NORMALIZERS.items() if normalizer is None]:
            del _TEXT_NORMALIZERS[code]
        for code, normalizer in own.items():
            if normalizer is not None:
                _TEXT_NORMALIZERS.setdefault(code, normalizer)
        model._text_normalizers = _TEXT_NORMALIZERS


def _load_magpie():
    """Load the model onto the active device and warm it (called by the slot, in a worker thread)."""
    global tts_model, model_loaded, _supported, _speaker_count
    logger.info("Loading Magpie-TTS model '%s' on %s...", MODEL_NAME, device)
    try:
        # NeMo is imported here, not at module level: it takes seconds to import and the
        # service must answer /health while it does.
        from nemo.collections.tts.models import MagpieTTSModel
        from nemo.collections.tts.parts.utils.tts_dataset_utils import LANGUAGE_TOKENIZER_MAP

        if os.path.isfile(MODEL_NAME):
            model = MagpieTTSModel.restore_from(restore_path=MODEL_NAME)
        else:
            model = MagpieTTSModel.from_pretrained(model_name=MODEL_NAME)
        model.eval()
        if device == "cuda":
            model = model.to("cuda")
        _share_text_normalizers(model)

        languages = supported_languages(LANGUAGE_TOKENIZER_MAP, model.tokenizer.tokenizers.keys())
        count = getattr(model, "num_baked_speakers", None)
        if not getattr(model, "has_baked_context_embedding", True) or not count:
            raise RuntimeError(
                "This checkpoint has no baked speakers, so do_tts cannot be used. "
                "Point MAGPIE_MODEL at a multilingual Magpie checkpoint with built-in speakers."
            )
        with _state_lock:
            _supported, _speaker_count = languages, int(count)
        tts_model, model_loaded = model, True
        logger.info(
            "Magpie-TTS loaded on %s: languages %s, %d speakers", device, languages, int(count)
        )
        _warm_up(model, languages)
        return model
    except Exception as e:
        logger.error("Failed to load Magpie-TTS model: %s", e, exc_info=True)
        raise


def _warm_up(model, languages) -> None:
    """One short generation per warm-up language still without a normalizer, so no user request pays for the build.

    The default language always goes first; MAGPIE_WARM_LANGUAGES adds more. A language the
    model cannot speak is skipped with a warning, and a generation that fails is not fatal:
    the model is loaded and the first request in that language would simply be slow.
    A language whose normalizer an earlier load or request already built is skipped, so
    in practice only the first load warms anything (``_share_text_normalizers``). The
    skip looks at what was really built, so a NeMo that keeps no normalizers where this
    service can see them warms on every load.
    """
    wanted = [DEFAULT_LANGUAGE] + [code for code in WARM_LANGUAGES if code != DEFAULT_LANGUAGE]
    for code in wanted:
        if code not in languages:
            logger.warning(
                "Not warming '%s': this model cannot speak it (supported: %s)%s",
                code, languages,
                "; requests without a language will be refused until MAGPIE_DEFAULT_LANGUAGE is changed."
                if code == DEFAULT_LANGUAGE else ".",
            )
            continue
        if APPLY_TN and _TEXT_NORMALIZERS.get(code) is not None:
            continue  # built by an earlier load or request: nothing left to warm
        try:
            started = time.monotonic()
            with _MODEL_LOCK:
                model.do_tts("Hallo.", language=code, apply_TN=APPLY_TN, use_cfg=USE_CFG, speaker_index=0)
            logger.info("Warm-up generation in '%s' took %.1fs", code, time.monotonic() - started)
        except Exception as e:
            logger.warning("Warm-up generation in '%s' failed (%s); its first request will be slower.", code, e)


def _release_magpie(model) -> None:
    """Clear the module aliases and get the weights off the GPU.

    Moving to CPU before dropping the object is deliberate: ``empty_cache()`` only
    returns blocks that are already unreferenced, so it frees nothing while any
    reference survives, and NeMo registers every instantiated model in its own
    ``AppState``. ``.cpu()`` releases the device allocation whoever still points at it.
    """
    global tts_model, model_loaded
    tts_model = None
    model_loaded = False
    try:
        model.cpu()
    except Exception as e:
        logger.warning("Could not move Magpie-TTS off the GPU before unload: %s", e)


# Idle TTS models are the largest single VRAM saving available when several services
# share one card: ~4.2 GB at the card here (1.75 GB of tensors). Reference counted, so a
# generation in flight is never unloaded underneath itself.
#   >0 = seconds idle before unloading | 0 = unload immediately | -1 = never
MODEL_TTL = ttl_from_env(os.getenv, "TTS_MODEL_TTL", "MODEL_TTL", default=300.0)
_model_slot = ModelSlot(
    _load_magpie, ttl_seconds=MODEL_TTL, name="Magpie-TTS", on_unload=_release_magpie,
)


async def _preload_model() -> None:
    """Load the model in the background so /health answers while it downloads.

    A first start fetches ~2.5 GB from Hugging Face (the model, its audio codec and
    two helper models),
    which can outlast the healthcheck's start period; /ready (503 "loading") is what
    reports it. The lease is released straight away, which arms the idle timer: with the
    default TTL an untouched service frees its VRAM ~5 minutes after boot. Set
    TTS_MODEL_TTL=-1 to keep it resident.
    """
    global _preload_pending
    try:
        lease = await _model_slot.acquire_lease()
    except asyncio.CancelledError:
        raise
    except Exception as e:
        logger.warning("Could not preload model: %s", e)
        return
    finally:
        _preload_pending = False
    await lease.release_async()


@asynccontextmanager
async def _lifespan(_app: FastAPI):
    global _preload_pending
    _preload_pending = True
    preload = asyncio.create_task(_preload_model())
    try:
        yield
    finally:
        preload.cancel()
        with suppress(asyncio.CancelledError):
            await preload
        await _model_slot.unload_async()


app = FastAPI(
    title="Magpie-TTS Service",
    description="Multilingual text-to-speech with NVIDIA Magpie-TTS (built-in speakers, no cloning)",
    lifespan=_lifespan,
)


def _body_limit(path: str) -> int:
    """Largest request body (bytes) accepted at *path*: JSON text only, no uploads."""
    # 12 bytes per character is the worst case, a JSON-escaped astral character.
    return MAX_TEXT_CHARS * 12 * 2 + 64 * 1024


